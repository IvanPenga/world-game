def dirt(x, y):
    if (x, y) in ((3, 2), (11, 3), (6, 7), (14, 9), (2, 13), (9, 14)):
        return 'o'
    if (x + y * 3) % 29 == 0:
        return 'd'
    return 'B'


tiles[26] = ('Dirt', None, gen(dirt))


def cobblestone(x, y):
    if x in (0, 15) or y in (0, 15):
        return 'm'
    if (x + (y // 4) * 3) % 5 == 0 or y % 4 == 0:
        return 'a'
    return 'l'


tiles[27] = ('Cobblestone', None, gen(cobblestone))


def cave_floor(x, y):
    if (x + y * 2) % 17 == 0:
        return 'm'
    if (x * 3 + y) % 23 == 0:
        return 'l'
    return 'a'


tiles[28] = ('Cave floor', None, gen(cave_floor))


def cave_wall(x, y):
    if y in (14, 15):
        return 'm'
    if y % 5 == 4 or x % 7 == 0:
        return 'K'
    if (x + y) % 6 == 0:
        return 'l'
    return 'a'


