def bridge(x, y):
    if y in (0, 15):
        return 'd'
    if y in (1, 14):
        return 'o'
    if x % 4 == 3:
        return 'd'
    if y == 2:
        return 'L'
    if y == 13:
        return 'o'
    return 'B'


