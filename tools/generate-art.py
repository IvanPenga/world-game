def grid(s):
    rows = [r for r in s.strip('\n').split('\n') if r.strip()]
    rows = [r.split()[-1] if ' ' in r.strip() else r.strip() for r in rows]
    assert len(rows) == 16, (len(rows), rows)
    for r in rows:
        assert len(r) == 16, (len(r), r)
    return rows


def gen(fn):
    return [''.join(fn(x, y) for x in range(16)) for y in range(16)]


