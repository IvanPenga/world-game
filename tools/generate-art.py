def rects(rows, ox, oy, pal):
    """Merge runs: horizontal runs, then stack identical runs vertically."""
    runs = {}  # (x, w, colour) -> list of y
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < 16:
            ch = row[x]
            if ch == '.':
                x += 1
                continue
            x2 = x
            while x2 < 16 and row[x2] == ch:
                x2 += 1
            out.append((x, y, x2 - x, 1, pal[ch]))
            x = x2
    # vertical merge of identical runs
    out.sort(key=lambda r: (r[0], r[2], r[4], r[1]))
    merged = []
    for r in out:
        if merged:
            m = merged[-1]
            if m[0] == r[0] and m[2] == r[2] and m[4] == r[4] and m[1] + m[3] == r[1]:
                merged[-1] = (m[0], m[1], m[2], m[3] + 1, m[4])
                continue
        merged.append(r)
    merged.sort(key=lambda r: (r[1], r[0]))
    by_col = {}
    for x, y, w, h, c in merged:
        by_col.setdefault(c, []).append((x + ox, y + oy, w, h))
    return by_col


def svg(cells, width, height, comments):
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
             f'viewBox="0 0 {width} {height}" shape-rendering="crispEdges">']
    for (rows, ox, oy, pal), comment in zip(cells, comments):
        parts.append(f'  <!-- {comment} -->')
        for colour, rs in rects(rows, ox, oy, pal).items():
            body = ''.join(
                f'<rect x="{x}" y="{y}" width="{w}" height="{h}"/>' for x, y, w, h in rs)
            parts.append(f'  <g fill="{colour}">{body}</g>')
    parts.append('</svg>')
    return '\n'.join(parts) + '\n'


def png(pixels, width, height, scale, path):
    import zlib, struct
    raw = bytearray()
    for y in range(height * scale):
        raw.append(0)
        for x in range(width * scale):
            raw.extend(pixels[y // scale][x // scale])
    def chunk(t, d):
        c = struct.pack('>I', len(d)) + t + d
        return c + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    data = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width * scale, height * scale, 8, 6, 0, 0, 0))
    data += chunk(b'IDAT', zlib.compress(bytes(raw), 9)) + chunk(b'IEND', b'')
    open(path, 'wb').write(data)


