def preview(directory):
    def hexrgb(c):
        return (int(c[1:3], 16), int(c[3:5], 16), int(c[5:7], 16), 255)
    def sheet(cells, w, h, bg):
        px = [[bg((x, y)) for x in range(w)] for y in range(h)]
        for rows, ox, oy, pal in cells:
            for y, r in enumerate(rows):
                for x, ch in enumerate(r):
                    if ch != '.':
                        px[oy + y][ox + x] = hexrgb(pal[ch])
        return px
    chk = lambda p: (200, 200, 200, 255) if ((p[0] // 4 + p[1] // 4) % 2) else (240, 240, 240, 255)
    grass = lambda p: hexrgb(TP['G'])
    tile_count = max(tiles)
    tile_height = ((tile_count + 3) // 4) * 16
    tc = [(tiles[t][2], ((t - 1) % 4) * 16, ((t - 1) // 4) * 16, TP) for t in range(1, tile_count + 1)]
    png(sheet(tc, 64, tile_height, chk), 64, tile_height, 8, os.path.join(directory, 'tiles.png'))
    cc = []
    for ri, cid in enumerate(SPRITES):
        pal = dict(CP_BASE, **CHAR_PAL[cid]); pal.setdefault('S', pal['s'])
        for ci, rows in enumerate(char_frames(cid)):
            cc.append((rows, ci * 16, ri * 16, pal))
    sprite_height = len(SPRITES) * 16
    png(sheet(cc, 64, sprite_height, chk), 64, sprite_height, 8, os.path.join(directory, 'chars.png'))
    png(sheet(cc, 64, sprite_height, grass), 64, sprite_height, 8, os.path.join(directory, 'chars_grass.png'))


