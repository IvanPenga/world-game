def lines(s):
    return [r for r in s.strip('\n').split('\n')]


def frame(head, body):
    rows = lines(head) + lines(body)
    assert len(rows) == 16, len(rows)
    for r in rows:
        assert len(r) == 16, (len(r), r)
    return rows


def char_frames(cid):
    h = HEADS[cid]
    bd, bu, bl = BODIES[cid]
    down = frame(h['down'], bd)
    up = frame(h['up'], bu)
    left = frame(h['left'], bl)
    right = [r[::-1] for r in left]
    return [down, up, left, right]


